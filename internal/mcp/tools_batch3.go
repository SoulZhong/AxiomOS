func init() {
	for k, v := range batch3Descs {
		toolDescs[k] = v
	}
}

func addBatch3Tools(s *sdk.Server, k *kit) {
	a, sess, f := k.a, k.sess, k.f
	sdk.AddTool(s, k.tool("propose_goal_plan"), func(ctx context.Context, req *sdk.CallToolRequest, in proposePlanIn) (*sdk.CallToolResult, any, error) {
		pi := app.GoalPlanInput{Rationale: in.Rationale}
		var err error
		if pi.GoalID, err = k.gid(ctx, in.GoalID); err != nil {
			return f(err)
		}
		if pi.GoalID == "" {
			return f(app.Bad("err.goal_missing"))
		}
		for _, t := range in.Tasks {
			pt := app.PlanTask{Key: t.Key, Title: t.Title, Description: t.Description, TypeName: t.TypeName, EstimateHours: t.EstimateHours, Priority: t.Priority,
				RequiredCapabilities: t.RequiredCapabilities, ParentKey: t.ParentKey, DependsOn: t.DependsOn, Acceptance: t.Acceptance}
			if pt.AssigneeID, err = k.mid(ctx, t.AssigneeID); err != nil {
				return f(err)
			}
			for slot, who := range t.Participants {
				id, err := k.mid(ctx, who)
				if err != nil {
					return f(err)
				}
				if pt.Participants == nil {
					pt.Participants = map[string]string{}
				}
				pt.Participants[slot] = id
			}
			if pt.PlannedStart, err = parseDate(t.PlannedStart); err != nil {
				return f(err)
			}
			if pt.PlannedEnd, err = parseDate(t.PlannedEnd); err != nil {
				return f(err)
			}
			pi.Tasks = append(pi.Tasks, pt)
		}
		for _, m := range in.Milestones {
			pm := app.PlanMilestone{Key: m.Key, Title: m.Title, Description: m.Description}
			if pm.DueOn, err = parseDate(m.DueOn); err != nil {
				return f(err)
			}
			pi.Milestones = append(pi.Milestones, pm)
		}
		v, err := a.ProposeGoalPlan(ctx, k.ws(in.DryRun, in.IdempotencyKey), pi)
		if err != nil {
			return f(err)
		}
		// 方案永远是一条待确认操作：走与其他工具一样的「已提交待确认操作」返回
		return f(app.PendingOf(sess, v))
	})
	sdk.AddTool(s, k.tool("get_goal_plan_status"), func(ctx context.Context, req *sdk.CallToolRequest, in planStatusIn) (*sdk.CallToolResult, any, error) {
		out, err := a.GoalPlanStatusOf(ctx, sess, in.ProposalID)
		if err != nil {
			return f(err)
		}
		return jsonResult(out)
	})
}
