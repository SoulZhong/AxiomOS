// 目标方案（ADR 0026）：Agent「领取目标」= 提交一整套拆解，目标负责人逐条勾选后一次落库。

type planTaskIn struct {
	Key                  string   `json:"key,omitempty" jsonschema:"Key of this task inside the plan (t1, t2...); depends_on and parent_key refer to it. Generated by position when omitted"`
	Title                string   `json:"title" jsonschema:"Title"`
	Description          string   `json:"description,omitempty" jsonschema:"Description"`
	TypeName             string   `json:"type_name,omitempty" jsonschema:"Task type code name, default generic"`
	EstimateHours        *float64 `json:"estimate_hours,omitempty" jsonschema:"Estimate in hours"`
	PlannedStart         string   `json:"planned_start,omitempty" jsonschema:"Planned start YYYY-MM-DD"`
	PlannedEnd           string   `json:"planned_end,omitempty" jsonschema:"Planned end YYYY-MM-DD"`
	Priority             *int     `json:"priority,omitempty" jsonschema:"Priority 0 (highest) to 3"`
	RequiredCapabilities []string `json:"required_capabilities,omitempty" jsonschema:"Capabilities required to claim"`
	AssigneeID           string   `json:"assignee_id,omitempty" jsonschema:"Assignee (@name, ID or email); defaults to me"`
	ParentKey            string   `json:"parent_key,omitempty" jsonschema:"Key of the parent task in this plan (makes this a subtask)"`
	DependsOn            []string `json:"depends_on,omitempty" jsonschema:"Keys of tasks in this plan that must finish first"`
	// ADR 0028
	Acceptance   string            `json:"acceptance,omitempty" jsonschema:"auto (default: the system accepts when the review step's requirements are met) or human (the goal owner reviews it in the plan review)"`
	Participants map[string]string `json:"participants,omitempty" jsonschema:"Participant slot -> person (@name, ID or email) for task types with slots; omitted slots are filled with the assignee"`
}

type planMilestoneIn struct {
	Key         string `json:"key,omitempty" jsonschema:"Key inside the plan (m1, m2...); generated by position when omitted"`
	Title       string `json:"title" jsonschema:"What should be achieved by that date"`
	DueOn       string `json:"due_on" jsonschema:"Date YYYY-MM-DD"`
	Description string `json:"description,omitempty" jsonschema:"Optional description"`
}

type proposePlanIn struct {
	GoalID         string            `json:"goal_id" jsonschema:"Goal reference: the goal ID or part of its title"`
	Rationale      string            `json:"rationale,omitempty" jsonschema:"Why this breakdown: what you read, what you assume, what you left out"`
	Tasks          []planTaskIn      `json:"tasks" jsonschema:"The tasks, in the order you would present them"`
	Milestones     []planMilestoneIn `json:"milestones,omitempty" jsonschema:"Milestones to add to the goal"`
	DryRun         bool              `json:"dry_run,omitempty" jsonschema:"Only say what would happen; every check still runs, nothing is written"`
	IdempotencyKey string            `json:"idempotency_key,omitempty" jsonschema:"Client-generated key (max 64 chars): the same key within 24 hours takes effect only once"`
}

type planStatusIn struct {
	ProposalID string `json:"proposal_id" jsonschema:"The pending action ID returned by propose_goal_plan (prp_...)"`
}

