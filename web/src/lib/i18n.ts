const DICT: Record<Locale, Record<Key, string>> = { "zh-CN": zh, "en-US": en };

// ---------- 当前语言（模块级存储） ----------
let current: Locale = "zh-CN";
let resolved = false;
const listeners = new Set<() => void>();

export function normalizeLocale(v: string | null | undefined): Locale | null {
  if (!v) return null;
  const s = v.toLowerCase();
  if (s.startsWith("zh")) return "zh-CN";
  if (s.startsWith("en")) return "en-US";
  return null;
}

function resolveInitial(): Locale {
  try {
    const stored = normalizeLocale(window.localStorage.getItem(STORAGE_KEY));
    if (stored) return stored;
  } catch {
    /* 隐私模式等情况下 localStorage 不可用 */
  }
  return normalizeLocale(typeof navigator !== "undefined" ? navigator.language : null) ?? "en-US";
}

/** 当前语言；服务端渲染时为 zh-CN。 */
export function getLocale(): Locale {
  if (!resolved && typeof window !== "undefined") {
    current = resolveInitial();
    resolved = true;
  }
  return current;
}

/** 切换语言并写入 localStorage；是否同步到后端由调用方决定。 */
export function setLocale(l: Locale) {
  resolved = true;
  if (l === current) return;
  current = l;
  try {
    window.localStorage.setItem(STORAGE_KEY, l);
  } catch {
    /* ignore */
  }
  listeners.forEach((fn) => fn());
}

export type Params = Record<string, string | number | null | undefined>;

export function t(key: Key, params?: Params): string {
  const s = DICT[current][key] ?? DICT["zh-CN"][key] ?? key;
  if (!params) return s;
  return s.replace(/\{(\w+)\}/g, (_, k: string) => (params[k] === undefined || params[k] === null ? "" : String(params[k])));
}

// ---------- React 侧 ----------
interface LocaleCtx {
  locale: Locale;
  setLocale: (l: Locale) => void;
}
const Ctx = createContext<LocaleCtx>({ locale: "zh-CN", setLocale });

export function useLocale(): LocaleCtx {
  return useContext(Ctx);
}

const subscribe = (cb: () => void) => {
  listeners.add(cb);
  return () => listeners.delete(cb);
};

/**
 * 在客户端解析语言后再渲染子树（服务端与水合阶段先渲染空，避免文案不一致）；
 * 语言切换时以 key 重挂子树，模块级 t() 的结果随之刷新。
 */
export function LocaleProvider({ children }: { children: ReactNode }) {
  const locale = useSyncExternalStore(subscribe, getLocale, () => null);
  useEffect(() => {
    if (locale) document.documentElement.lang = locale;
  }, [locale]);
  if (!locale) return null;
  return createElement(Ctx.Provider, { value: { locale, setLocale } }, createElement(Fragment, { key: locale }, children));
}
